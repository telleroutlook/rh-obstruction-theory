    print(f"\n  (A) all-match: {all_ok}")

    print("\n" + "=" * 72)
    print("(B)+(C) Rebuild a real LLL collision as a vanishing-moment identity,")
    print("        and check the Chebyshev bound  sum_online|c| >= |q*|*|T_m(u*)|.")
    print("=" * 72)

    def shortest_rel_custom(ts, dvec, m, weight_bits=24):
        vecs = [P.C_vec(t, m) for t in ts] + [dvec]
        K1 = len(vecs); Lden = 1
        for v in vecs:
            for x in v:
                Lden = Lden * x.denominator // math.gcd(Lden, x.denominator)
        Vint = [[int(x * Lden) for x in v] for v in vecs]
        w = 1 << weight_bits; basis = []
        for i in range(K1):
            row = [0] * K1 + [w * c for c in Vint[i]]; row[i] = 1; basis.append(row)
        red = P.lll(basis); best = None
        for row in red:
            c = row[:K1]; tail = row[K1:]
            if any(tail) or c[-1] == 0:
                continue
            mc = max(abs(v) for v in c)
            if best is None or mc < best[2]:
                best = (c[:-1], c[-1], mc)
        return best

