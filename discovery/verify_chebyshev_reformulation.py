# ---- exact complex-rational T_j(u) for u = ur + i*ui (Fractions) ----
def cheb_T_complex(j, ur, ui):
    """T_j(u), u = ur + i ui, exact Fraction real/imag. T_0=1,T_1=u,rec."""
    if j == 0:
        return Fr(1), Fr(0)
    a_r, a_i = Fr(1), Fr(0)          # T_0
    b_r, b_i = ur, ui                # T_1
    for _ in range(1, j):
        # T_{k+1} = 2u T_k - T_{k-1}
        two_u_Tk_r = 2 * (ur * b_r - ui * b_i)
        two_u_Tk_i = 2 * (ur * b_i + ui * b_r)
        c_r, c_i = two_u_Tk_r - a_r, two_u_Tk_i - a_i
        a_r, a_i, b_r, b_i = b_r, b_i, c_r, c_i
    return b_r, b_i


def w_and_u(sigma, tau):
    """rho = sigma + i tau (Fractions).  w = 1 - 1/rho.  u = (w + 1/w)/2.
    Returns (u_r, u_i) exact."""
    sigma, tau = Fr(sigma), Fr(tau)
    # 1/rho = conj(rho)/|rho|^2
    den = sigma * sigma + tau * tau
    inv_r, inv_i = sigma / den, -tau / den
    w_r, w_i = 1 - inv_r, -inv_i
    # 1/w
    wden = w_r * w_r + w_i * w_i
    iw_r, iw_i = w_r / wden, -w_i / wden
    u_r = (w_r + iw_r) / 2
    u_i = (w_i + iw_i) / 2
    return u_r, u_i


def O_orbit_direct(sigma, tau, m):
    """O_j of the orbit {sigma±i tau, (1-sigma)±i tau} via the phi definition
    (the same convention as the certified checker), for j=1..m."""
    sigma, tau = Fr(sigma), Fr(tau)
    atoms = [(sigma, tau), (sigma, -tau), (1 - sigma, tau), (1 - sigma, -tau)]
    out = []
    for j in range(1, m + 1):
        s = Fr(0)
        for (re, im) in atoms:
            for (r2, i2) in ((re, im), (1 - re, im)):
                s += P._phi_re(j, r2, i2)
        out.append(s)
    return out


if __name__ == "__main__":
    print("=" * 72)
    print("(A) Verify  O_j(orbit) = 8 (1 - Re T_j(u)),  u = (w+1/w)/2, w=1-1/rho")
